# String3: Дан символ C. Вывести символ, предшествующий C и следующий за ним
C = input("Введите символ C: ")
print(chr(ord(C) - 1), chr(ord(C) + 1))

# String4: Дано N (1 ≤ N ≤ 26). Вывести строку из N первых заглавных латинских букв
N = int(input("Введите N (1-26): "))
print("".join(chr(i) for i in range(ord("A"), ord("A") + N)))

# String5: Дано N (1 ≤ N ≤ 26). Вывести строку из N последних строчных латинских букв
# в обратном порядке, начиная с "z"
N = int(input("Введите N (1-26): "))
print("".join(chr(i) for i in range(ord("z"), ord("z") - N, -1)))

