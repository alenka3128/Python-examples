# String12: Дана непустая строка S и N (> 0). Вывести строку из символов S,
# между которыми вставлено по N звёздочек
S = input("Введите строку S: ")
N = int(input("Введите N: "))
print(("*" * N).join(S))

# String14: Дана строка. Подсчитать количество прописных латинских букв в ней
S = input("Введите строку: ")
count = sum(1 for c in S if "A" <= c <= "Z")
print(f"Прописных латинских букв: {count}")

